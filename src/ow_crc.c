uint8_t ow_crc8(const uint8_t *data, uint8_t len)
{
    uint8_t crc = 0u;

    for (uint8_t i = 0u; i < len; i++) {
        crc = crc8_tab[(uint8_t)(crc ^ data[i])];
    }
    return crc;
}

